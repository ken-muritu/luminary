#!/usr/bin/env bash
# Provision Luminary cloud database on Turso (optional — app defaults to local SQLite).
set -euo pipefail

DB_NAME="${LUMINARY_TURSO_DB_NAME:-luminary-db}"
LOCATION="${LUMINARY_TURSO_LOCATION:-aws-eu-west-1}"
ENV_FILE="${1:-${HOME}/.config/luminary/.env}"
mkdir -p "$(dirname "$ENV_FILE")"

if ! command -v turso >/dev/null 2>&1; then
  echo "turso CLI not found. Install: curl -sSfL https://get.tur.so/install.sh | bash"
  exit 1
fi

echo "Authenticated as: $(turso auth whoami 2>/dev/null || echo 'not logged in')"
echo "Creating database '${DB_NAME}' in ${LOCATION}…"

if turso db show "$DB_NAME" >/dev/null 2>&1; then
  echo "Database '${DB_NAME}' already exists."
else
  turso db create "$DB_NAME" --location "$LOCATION"
fi

URL="$(turso db show "$DB_NAME" --url)"
TOKEN="$(turso db tokens create "$DB_NAME")"

cat > "$ENV_FILE" <<EOF
# Luminary Turso (generated by scripts/setup-turso.sh)
LUMINARY_TURSO_URL=${URL}
LUMINARY_TURSO_AUTH_TOKEN=${TOKEN}
EOF

echo "Wrote ${ENV_FILE}. Restart Luminary with these env vars to use cloud sync."
echo "URL: ${URL}"
