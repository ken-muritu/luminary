#!/usr/bin/env bash
# Build Luminary and install a searchable desktop launcher (Linux).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

APP_NAME="luminary"
CONFIG_DIR="${HOME}/.config/${APP_NAME}"
LOCAL_BIN="${HOME}/.local/bin"
DESKTOP_DIR="${HOME}/.local/share/applications"
ICON_DIR="${HOME}/.local/share/icons/hicolor/256x256/apps"
INSTALL_DIR="${HOME}/.local/opt/luminary"

echo "═══════════════════════════════════════"
echo " Luminary Desktop Install"
echo "═══════════════════════════════════════"

mkdir -p "$CONFIG_DIR" "$LOCAL_BIN" "$DESKTOP_DIR" "$ICON_DIR" "$INSTALL_DIR"

# ── Turso config (optional cloud DB) ───────────────────────────────────────
if command -v turso >/dev/null 2>&1 && turso db show luminary-db >/dev/null 2>&1; then
  TURSO_URL="$(turso db show luminary-db --url)"
  TURSO_TOKEN="$(turso db tokens create luminary-db 2>/dev/null | tail -1)"
  cat > "${CONFIG_DIR}/.env" <<EOF
# Luminary database — Turso cloud (generated by install-luminary.sh)
LUMINARY_TURSO_URL=${TURSO_URL}
LUMINARY_TURSO_AUTH_TOKEN=${TURSO_TOKEN}
EOF
  echo "✓ Turso config → ${CONFIG_DIR}/.env"
  echo "  URL: ${TURSO_URL}"
else
  echo "○ Turso not configured — using local DB at ${CONFIG_DIR}/luminary.db"
  echo "  Run: ./scripts/setup-turso.sh to enable cloud later"
fi

# ── Build production app ─────────────────────────────────────────────────────
echo ""
echo "Building Luminary (this may take a few minutes)…"
npm run build
npm run dist -- --linux

APPIMAGE="$(find dist-electron -maxdepth 1 -name 'Luminary-*.AppImage' | head -1)"
UNPACKED="$(find dist-electron -maxdepth 1 -type d -name 'linux-unpacked' | head -1)"

if [[ -n "$APPIMAGE" && -f "$APPIMAGE" ]]; then
  cp "$APPIMAGE" "${INSTALL_DIR}/Luminary.AppImage"
  chmod +x "${INSTALL_DIR}/Luminary.AppImage"
  EXEC="${INSTALL_DIR}/Luminary.AppImage"
  echo "✓ AppImage → ${EXEC}"
elif [[ -n "$UNPACKED" && -f "${UNPACKED}/luminary" ]]; then
  rm -rf "${INSTALL_DIR}/app"
  cp -a "$UNPACKED" "${INSTALL_DIR}/app"
  EXEC="${INSTALL_DIR}/app/luminary"
  echo "✓ Unpacked build → ${EXEC}"
else
  echo "✗ Build failed — no AppImage or linux-unpacked found in dist-electron/"
  exit 1
fi

# ── Icon + .desktop launcher ─────────────────────────────────────────────────
cp "${ROOT}/build/icon.png" "${ICON_DIR}/${APP_NAME}.png"

cat > "${DESKTOP_DIR}/luminary.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=Luminary
Comment=Church presentation software
Exec=${EXEC} %U
Icon=${APP_NAME}
Terminal=false
Categories=AudioVideo;Presentation;Office;
StartupWMClass=luminary
Keywords=church;worship;presentation;bible;projector;
EOF

chmod +x "${DESKTOP_DIR}/luminary.desktop"
install -m 755 "${ROOT}/scripts/luminary-launcher.sh" "${LOCAL_BIN}/luminary"

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "${HOME}/.local/share/applications" 2>/dev/null || true
fi

echo ""
echo "═══════════════════════════════════════"
echo " ✓ Luminary installed!"
echo ""
echo " Launch: search 'Luminary' in your app menu"
echo "         or run: ${EXEC}"
echo ""
if [[ -f "${CONFIG_DIR}/.env" ]]; then
  echo " Database: Turso (luminary-db)"
  echo " First launch seeds Bible — may take ~1 min."
else
  echo " Database: local ${CONFIG_DIR}/luminary.db"
fi
echo "═══════════════════════════════════════"
